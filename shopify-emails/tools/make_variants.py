"""Write the delivery-stage notifications from the shipping-confirmation base (English + Arabic).
Run after tools/make_arabic.py so the Arabic base is current."""
import pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
BASE_STAGE = "{%- assign stage = 'shipped' -%}\n{%- assign is_local = false -%}"
VARIANTS = [
    # file stem                 stage               local   Shopify notification name
    ("shipping-out-for-delivery", "out_for_delivery", False, "Shipping update: Out for delivery ('A shipment from order {{ name }} is out for delivery')"),
    ("shipping-delivered",        "delivered",        False, "Shipping update: Delivered ('A shipment from order {{ name }} has been delivered')"),
    ("local-out-for-delivery",    "out_for_delivery", True,  "Local delivery: Out for delivery ('Order {{ name }} is out for delivery')"),
    ("local-delivered",           "delivered",        True,  "Local delivery: Delivered ('Order {{ name }} has been delivered')"),
]
for suffix in ("", ".ar"):
    base = (ROOT / f"shipping-confirmation{suffix}.liquid").read_text()
    if BASE_STAGE not in base:
        sys.exit(f"stage lines not found in shipping-confirmation{suffix}.liquid")
    for stem, stage, local, label in VARIANTS:
        out = base.replace(BASE_STAGE, f"{{%- assign stage = '{stage}' -%}}\n{{%- assign is_local = {'true' if local else 'false'} -%}}")
        out = f"{{%- comment -%}} NOTIFICATION: {label}{' — ARABIC (paste in Translate & Adapt)' if suffix else ''}. Generated by tools/make_variants.py {{%- endcomment -%}}\n" + out
        (ROOT / f"{stem}{suffix}.liquid").write_text(out)
        print("wrote", f"{stem}{suffix}.liquid")
